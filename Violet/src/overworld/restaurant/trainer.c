u16 restaurant_get_random_species(u8 type, u8 level, size_t num_choices, u16 *choices) {
    u16 *list = malloc_and_clear(POKEMON_CNT * sizeof(u16));
    u32 num_found = 0;
    for (size_t i = 0; restaurant_species[i].species != 0xFFFF; i++) {
        if (restaurant_species[i].appears_at_level <= level &&
            (type == NUM_TYPES 
                || basestats[restaurant_species[i].species].type1 == type
                || basestats[restaurant_species[i].species].type2 == type)) {
            list[num_found++] = restaurant_species[i].species;
        }
    }
    u16 num_chosen = 0;
    while(num_chosen < num_choices && num_found > 0) {
        u16 idx = (u16)(rnd16() % num_found);
        choices[num_chosen++] = list[idx];
        // Don't resample this pokemon
        list[idx] = list[--num_found];
    }
    free(list);
    return num_chosen;
};

u8 restaurant_setup_trainer_party(u16 trainer_idx) {
    u32 seq[] = {
        trainer_idx, 
        *var_access(VAR_RESTAURANT_TYPE),
        *var_access(VAR_RESTAURANT_LEVEL),
        *var_access(VAR_RESTAURANT_STARTER),
        0xDEADBEEF};
    gp_rng = hash_sequence(seq, ARRAY_COUNT(seq), *var_access(VAR_RESTAURANT_SEED));
    DEBUG("restaurant_setup_trainer_party: trainer_idx=%d, type=%d, level=%d, starter=%d, seed=%d\n", 
        trainer_idx, *var_access(VAR_RESTAURANT_TYPE), *var_access(VAR_RESTAURANT_LEVEL), 
        *var_access(VAR_RESTAURANT_STARTER), *var_access(VAR_RESTAURANT_SEED));
    u16 species[6];
    u16 num_species = restaurant_get_random_species(
        (u8)(*var_access(VAR_RESTAURANT_TYPE)), 
        (u8)(*var_access(VAR_RESTAURANT_LEVEL)),
        ARRAY_COUNT(dynamic_trainer_party), species);
    memset(dynamic_trainer_party, 0, sizeof(dynamic_trainer_party));
    for (u16 i = 0; i < num_species; i++) {
        dynamic_trainer_party[i].species = species[i];
        dynamic_trainer_party[i].level = (u8)MAX(2, MIN(100, 
            restaurant_levels[*var_access(VAR_RESTAURANT_LEVEL)] - 2 + (gp_rnd16() % 4)
        ));
        for (u8 j = 0; j < 6; j++)
            dynamic_trainer_party[i].ivs[j] = 0;
    }
    return (u8)num_species;
}
