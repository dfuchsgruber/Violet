static u8 person_behaviour_oam_callback_no_behaviour_step_0(npc *n, oam_object *o) {
    // Abuse the range to center the npc, interpret as signed int with 4 bits
    int signed_x = (n->rectangle.x & 0x8) ? (n->rectangle.x - 16) : n->rectangle.x;
    int signed_y = (n->rectangle.y & 0x8) ? (n->rectangle.y - 16) : n->rectangle.y;
    // o->final_oam.attr2 = (u16)((o->final_oam.attr2 & (~ATTR2_PRIO_MASK)) | ATTR2_PRIO(0));
    o->x2 = (s16)(signed_x);
    o->y2 = (s16)(signed_y);
    return false;
}

static void person_behaviour_oam_callback_no_behaviour(oam_object *oam) {
    npc_update_current_movement(npcs + (oam->private[0]),oam, person_behaviour_oam_callback_no_behaviour_step_0);
}


